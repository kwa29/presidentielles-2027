export function outlineToSvgPath(points: [number, number][]) {
  return (
    points
      .map(([x, y], index) => `${index === 0 ? "M" : "L"} ${x.toFixed(3)} ${(-y).toFixed(3)}`)
      .join(" ") + " Z"
  );
}
